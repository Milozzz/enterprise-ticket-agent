def build_extended_policy_docs() -> list[dict]:
    documents: list[dict] = []
    sequence = 11
    for domain, domain_title, clauses in _POLICY_DOMAINS:
        for clause_title, clause_text in clauses:
            policy_id = f"P{sequence:03d}"
            documents.append(
                {
                    "id": policy_id,
                    "title": f"{domain_title} - {clause_title}",
                    "content": f"【{policy_id} {clause_title}】{clause_text}",
                    "source": f"ENTERPRISE_POLICY/{domain}",
                    "permission_roles": ["USER", "AGENT", "MANAGER", "SECURITY", "FINANCE"],
                }
            )
            sequence += 1
    return documents


EXTENDED_POLICY_DOCS = build_extended_policy_docs()
